<?php

namespace Database\Seeders;

use App\Models\Subject;
use App\Models\Topic;
use Illuminate\Database\Seeder;

class TopicSeeder extends Seeder
{
    /**
     * موضوعات واقعی هر درس، بر اساس انواع سؤالات رایج در آزمون تیزهوشان.
     * چون بعضی درس‌ها (مثل «هوش تصویری و فضایی») هم زیر پایه‌ی ششم و هم نهم
     * تعریف شدن، این لیست بر اساس عنوان درس اعمال می‌شه، نه پایه‌ی خاص.
     */
    public function run(): void
    {
        $topicsBySubject = [
            'هوش تصویری و فضایی' => [
                'تشخیص شکل متفاوت',
                'تکمیل الگوی تصویری',
                'چرخش و تقارن اشکال',
                'مکعب و تجسم فضایی',
                'قیاس تصویری',
            ],
            'هوش کلامی و ادبی' => [
                'تشابه و تضاد کلمات',
                'قیاس کلامی',
                'طبقه‌بندی کلمات (کلمه‌ی متفاوت)',
                'تکمیل جمله و ترتیب منطقی',
            ],
            'هوش محاسباتی و منطقی' => [
                'الگو و توالی اعداد',
                'روابط و معادلات ساده',
                'مسائل کلامی ریاضی',
                'استدلال منطقی-عددی',
            ],
            'سرعت و دقت' => [
                'تطبیق سریع نمادها و اعداد',
                'یافتن تفاوت‌های جزئی در تصاویر مشابه',
                'شمارش سریع',
            ],
            'ریاضی' => [
                'کسرها و اعداد اعشاری',
                'هندسه',
                'الگوها',
                'مسائل کلامی',
            ],
            'علوم' => [
                'زیست‌شناسی پایه',
                'فیزیک و شیمی پایه',
                'زمین‌شناسی',
            ],
            'فارسی' => [
                'درک مطلب',
                'دستور زبان',
                'واژگان و املا',
            ],
            'مطالعات اجتماعی' => [
                'تاریخ',
                'جغرافیا',
                'مدنی',
            ],
        ];

        Subject::all()->each(function (Subject $subject) use ($topicsBySubject) {
            $topics = $topicsBySubject[$subject->title] ?? [];

            foreach ($topics as $index => $title) {
                Topic::firstOrCreate(
                    ['subject_id' => $subject->id, 'title' => $title],
                    ['sort_order' => $index + 1]
                );
            }
        });
    }
}
